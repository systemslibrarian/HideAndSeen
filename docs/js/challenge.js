(function () {
  "use strict";

  const element = id => document.getElementById(id);
  const cases = ["ordinary", "padding", "segmentation", "ecc", "encoder"];
  const mixedText = "MEET AT GATE 7 / CODE 86753091234567890";
  let current = null;

  function createCase(kind) {
    if (kind === "padding") {
      const symbol = QR.build("https://museum.example/visit/4821", { ecc: "M", secret: "SEEN" });
      return { kind, matrix: symbol.matrix, symbol, text: symbol.text, version: symbol.version,
        ecc: symbol.ecc, mask: symbol.mask, hidden: "SEEN",
        title: "Hidden data present",
        mechanism: "Pad codewords carry the text SEEN; parity was recomputed, so the QR remains internally valid.",
        useful: "Padding inspection finds departures from the alternating 0xEC / 0x11 pattern.",
        misleading: "ECC validation passes because the modified data has matching parity.",
        conclusion: "This sample contains a padding-channel payload." };
    }
    if (kind === "segmentation") {
      const variant = HideAndSeenSegments.variants(mixedText, "M")[2];
      return { kind, matrix: variant.symbol.matrix, symbol: variant.symbol,
        text: mixedText, version: variant.symbol.version, ecc: variant.symbol.ecc,
        mask: variant.symbol.mask, hidden: variant.bits,
        title: "Hidden selection signal present",
        mechanism: `Representation ${variant.bits} uses ${variant.segments.length} valid byte segments.`,
        useful: "Segmentation inspection shows a deliberately selected, non-minimal representation.",
        misleading: "Padding and Reed-Solomon parity are both valid; those clean checks do not address segmentation.",
        conclusion: "A cooperating mapping recovers two selection bits. Segment structure alone is evidence of representation choice, not intent." };
    }
    if (kind === "ecc") {
      const symbol = QR.build("https://museum.example/visit/4821", { ecc: "M" });
      const mutation = HideAndSeenEcc.mutate(symbol, 5, 0, "10110");
      return { kind, matrix: mutation.matrix, symbol, mutation, text: symbol.text,
        version: symbol.version, ecc: symbol.ecc, mask: symbol.mask, hidden: mutation.hidden,
        title: "Controlled correctable changes present",
        mechanism: "Five distinct codewords contain one flipped module each; the changes encode 10110.",
        useful: "Reed-Solomon validation reports nonzero parity mismatches before correction.",
        misleading: "An ordinary decoder repairs the errors and reports only the overt URL.",
        conclusion: "The sample contains controlled errors within the correction budget." };
    }
    if (kind === "encoder") {
      const symbol = HideAndSeenEncoders.nodeQrcode(mixedText, { errorCorrectionLevel: "M" });
      return { kind, matrix: symbol.matrix, symbol, text: symbol.text, version: symbol.version,
        ecc: symbol.ecc, mask: symbol.mask, hidden: null,
        title: "No hidden data",
        mechanism: "An innocent QR generated by node-qrcode using its normal segmentation and mask choices.",
        useful: "Segment and ECC inspection show a valid optimized representation with intact parity.",
        misleading: "Regeneration with HideAndSeen differs because the reference encoder makes different default choices. Treating that difference as hidden data would be a false positive.",
        conclusion: "The sample is clean in this controlled case. A regeneration difference alone would be a false positive." };
    }
    const symbol = QR.build("https://museum.example/visit/4821", { ecc: "M" });
    return { kind: "ordinary", matrix: symbol.matrix, symbol, text: symbol.text,
      version: symbol.version, ecc: symbol.ecc, mask: symbol.mask, hidden: null,
      title: "No hidden data",
      mechanism: "An ordinary HideAndSeen QR with canonical padding and valid Reed-Solomon parity.",
      useful: "Padding, segment, parity, and same-engine regeneration checks are mutually consistent.",
      misleading: "No tested instrument produces a positive signal in this sample.",
      conclusion: "No hidden channel is present among the techniques implemented by this challenge. That is not a universal proof of absence." };
  }

  function inspect() {
    try {
      return HideAndSeenInspect.inspect(current.matrix, current.version, current.ecc, current.mask);
    } catch (error) {
      return { error };
    }
  }

  function paddingReport(parsed) {
    if (parsed.error) return { title: "Data stream needs correction first", detail: parsed.error.message };
    const body = parsed.padding[0] === 0 ? parsed.padding.slice(1) : parsed.padding;
    const wrong = body.filter((value, index) => value !== (index % 2 ? 0x11 : 0xec)).length;
    return {
      title: wrong ? "Padding anomaly detected" : "Padding matches the expected pattern",
      detail: `${body.length} pad codewords; ${wrong} differ from alternating EC / 11.`
    };
  }

  function segmentReport(parsed) {
    if (parsed.error) return { title: "Segment stream needs correction first", detail: parsed.error.message };
    const description = parsed.segments.map(segment => `${segment.mode}(${JSON.stringify(segment.text)})`).join(" + ");
    let expected = "";
    try {
      const efficient = HideAndSeenSegments.efficient(parsed.payload, current.ecc);
      expected = efficient.segments.map(segment => `${segment.mode}(${JSON.stringify(segment.text)})`).join(" + ");
    } catch (error) {
      expected = "optimizer unavailable";
    }
    return { title: `${parsed.segments.length} data segment${parsed.segments.length === 1 ? "" : "s"}`,
      detail: `Observed: ${description}\nEfficient model: ${expected}` };
  }

  function moduleMapReport() {
    const source = current.symbol.moduleMap || QR.functionMap(current.version);
    const highlights = [];
    const counts = {};
    source.forEach((row, rowIndex) => row.forEach((info, columnIndex) => {
      counts[info.role] = (counts[info.role] || 0) + 1;
      if (["payload", "padding", "error-correction"].includes(info.role))
        highlights.push({ row: rowIndex, column: columnIndex });
    }));
    HideAndSeenRender.draw(element("challengeQr"), current.matrix, { size: 400, dim: true, highlights });
    return { title: "Data-bearing module map", detail: Object.entries(counts).map(([role, count]) => `${role}: ${count}`).join("\n") };
  }

  function regenerationReport() {
    let reference;
    try {
      reference = QR.build(current.text, {
        version: current.version, ecc: current.ecc, mask: current.mask
      });
    } catch (error) {
      const automatic = QR.build(current.text, { ecc: current.ecc });
      return {
        title: "Visible size mismatch",
        detail: `The received symbol is v${current.version}-${current.ecc}; the reference encoder needs v${automatic.version}-${automatic.ecc} for the same overt message. ${error.message}.`
      };
    }
    const comparison = HideAndSeenEncoders.compare(current, reference);
    if (!comparison.comparable)
      return { title: "Visible size mismatch", detail: comparison.reason };
    HideAndSeenRender.draw(element("challengeQr"), current.matrix, {
      size: 400,
      dim: comparison.count > 0,
      highlights: comparison.differences
    });
    return { title: comparison.count ? "Regeneration difference" : "Exact regeneration match",
      detail: `${comparison.count} module differences against a HideAndSeen reference with the same version, ECC, and mask.` };
  }

  function runTool(tool) {
    HideAndSeenRender.draw(element("challengeQr"), current.matrix, { size: 400 });
    let report;
    const parsed = ["codewords", "padding", "segments"].includes(tool) ? inspect() : null;
    if (tool === "decode") {
      const decoded = HideAndSeenDecoder.decodeMatrix(current.matrix);
      report = { title: decoded ? "Ordinary decode succeeded" : "Ordinary decode failed",
        detail: decoded || "No overt payload recovered." };
    } else if (tool === "metadata") {
      report = { title: `Version ${current.version}-${current.ecc}, mask ${current.mask}`,
        detail: `${current.matrix.length} x ${current.matrix.length} modules; ${current.symbol.encoder || "HideAndSeen"} metadata is known to the case generator but not proof of origin.` };
    } else if (tool === "codewords") {
      report = parsed.error ? { title: "Raw stream extracted", detail: parsed.error.message } : {
        title: `${parsed.dataCodewords.length} data codewords`,
        detail: parsed.dataCodewords.slice(0, 48).map(value => value.toString(16).toUpperCase().padStart(2, "0")).join(" ") + (parsed.dataCodewords.length > 48 ? " ..." : "")
      };
    } else if (tool === "padding") report = paddingReport(parsed);
    else if (tool === "segments") report = segmentReport(parsed);
    else if (tool === "modules") report = moduleMapReport();
    else if (tool === "regenerate") report = regenerationReport();
    else if (tool === "ecc") {
      const verification = HideAndSeenInspect.verifyErrorCorrection(current.matrix, current.version, current.ecc, current.mask);
      report = { title: verification.valid ? "Reed-Solomon parity is internally consistent" : "ECC anomaly detected",
        detail: `${verification.invalidBlocks} of ${verification.blocks.length} blocks have parity mismatches${verification.valid ? "." : "; a decoder may repair the altered codewords."}` };
    }
    element("toolName").textContent = tool.toUpperCase().replaceAll("-", " ");
    element("toolFinding").textContent = report.title;
    element("toolDetail").textContent = report.detail;
    document.querySelectorAll("[data-tool]").forEach(button =>
      button.setAttribute("aria-pressed", String(button.dataset.tool === tool)));
  }

  function load(kind) {
    current = createCase(kind);
    element("caseReveal").hidden = true;
    const fallback = document.querySelector('input[name="verdict"][value="uncertain"]');
    if (fallback) fallback.checked = true;
    element("toolName").textContent = "NO INSTRUMENT SELECTED";
    element("toolFinding").textContent = "Begin with an ordinary decode or inspect the structure directly.";
    element("toolDetail").textContent = "Evidence will appear here.";
    element("challengeCaption").textContent = `UNKNOWN SAMPLE / v${current.version}-${current.ecc}`;
    HideAndSeenRender.draw(element("challengeQr"), current.matrix, { size: 400 });
    document.querySelectorAll("[data-tool]").forEach(button => button.setAttribute("aria-pressed", "false"));
  }

  function randomCase() {
    const forced = new URLSearchParams(location.search).get("case");
    if (forced && cases.includes(forced)) return forced;
    const values = new Uint32Array(1);
    crypto.getRandomValues(values);
    return cases[values[0] % cases.length];
  }

  const VERDICT_LABEL = {
    hidden: "Something is hidden",
    clean: "No hidden data",
    uncertain: "Evidence is inconclusive"
  };

  function chosenVerdict() {
    const picked = document.querySelector('input[name="verdict"]:checked');
    return picked ? picked.value : "uncertain";
  }

  // The case carries its own ground truth: `hidden` is null for clean samples.
  function scoreVerdict() {
    const node = element("caseScore");
    if (!node) return;
    const truth = current.hidden === null || current.hidden === undefined ? "clean" : "hidden";
    const said = chosenVerdict();
    let outcome;
    let note;

    if (said === truth) {
      outcome = "correct";
      note = truth === "clean"
        ? "Correct. Calling a sample clean is the harder judgement, and reporting that nothing was found is a real result."
        : "Correct, and the mechanism is named below.";
    } else if (said === "uncertain") {
      outcome = "partial";
      note = "Defensible, but the instruments could have settled this one. See USEFUL EVIDENCE below.";
    } else if (said === "hidden") {
      outcome = "wrong";
      note = "This is a false positive. Nothing is hidden in this sample, and the evidence that pointed that way has an innocent explanation. See MISLEADING EVIDENCE below.";
    } else {
      outcome = "wrong";
      note = "This is a miss. Something is hidden here, and one of the instruments would have shown it. See USEFUL EVIDENCE below.";
    }

    node.classList.remove("correct", "wrong", "partial");
    node.classList.add(outcome);
    node.textContent = `You said: ${VERDICT_LABEL[said]}. ${note}`;
    node.dataset.outcome = outcome;
  }

  function reveal() {
    scoreVerdict();
    element("caseTruth").textContent = current.title;
    element("caseMechanism").textContent = current.mechanism;
    element("caseUseful").textContent = current.useful;
    element("caseMisleading").textContent = current.misleading;
    element("caseConclusion").textContent = current.conclusion;
    element("caseReveal").hidden = false;
    element("caseReveal").scrollIntoView({ behavior: window.matchMedia && window.matchMedia("(prefers-reduced-motion: reduce)").matches ? "auto" : "smooth", block: "start" });
  }

  document.querySelectorAll("[data-tool]").forEach(button =>
    button.addEventListener("click", () => runTool(button.dataset.tool)));
  element("newCase").addEventListener("click", () => load(cases[(cases.indexOf(current.kind) + 1) % cases.length]));
  element("revealCase").addEventListener("click", reveal);
  load(randomCase());
})();
